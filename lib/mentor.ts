/** メンター（悩み相談のチャット「Monday」）の指示文・MBTI・安全のきまり */

export const MBTI_TYPES = ["INTJ", "INTP", "ENTJ", "ENTP", "INFJ", "INFP", "ENFJ", "ENFP", "ISTJ", "ISFJ", "ESTJ", "ESFJ", "ISTP", "ISFP", "ESTP", "ESFP"] as const;
export const isMbti = (v: unknown): v is (typeof MBTI_TYPES)[number] => typeof v === "string" && (MBTI_TYPES as readonly string[]).includes(v);

/** タイプごとの、話し方のコツ（Mondayの口調は変えず、相手に合わせて、関わり方だけ変える） */
const MBTI_TIPS: Record<string, string> = {
  I: "考えてから話すタイプ。急かさず、少し間を置いて聞く。質問は1つずつ。",
  E: "話しながら考えるタイプ。テンポよく、勢いに乗って話を広げる。",
  N: "全体像・意味・将来の話に反応する。「つまりどういうこと？」「この先どうなりたい？」が刺さる。",
  S: "具体例・事実・今日あった出来事に反応する。「いつ・誰が・何を言った？」と具体的に聞く。",
  T: "筋道・理由・納得感を大事にする。感情の話の前に、状況を整理してあげると楽になる。",
  F: "気持ち・人間関係・共感を大事にする。まず気持ちを受け止めてから、考えを整理する。",
  J: "決めて動きたいタイプ。最後に、小さな次の一歩を一緒に決めると安心する。",
  P: "選択肢を残したいタイプ。決めつけず「こんなやり方もあるよ」と幅を持たせる。",
};
export function mbtiTips(mbti: string): string {
  return mbti.split("").map((c) => MBTI_TIPS[c]).filter(Boolean).map((t) => `・${t}`).join("\n");
}

