import { describe, expect, it } from "vitest";
import { holidayName } from "../lib/holidays";

describe("祝日", () => {
  it("2026年の祝日", () => {
    const cases: [string, string | null][] = [
      ["2026-01-01", "元日"], ["2026-01-12", "成人の日"], ["2026-02-11", "建国記念の日"], ["2026-02-23", "天皇誕生日"], ["2026-03-20", "春分の日"],
      ["2026-04-29", "昭和の日"], ["2026-05-06", "振替休日"], ["2026-07-20", "海の日"], ["2026-08-11", "山の日"], ["2026-09-21", "敬老の日"],
      ["2026-09-22", "国民の休日"], ["2026-09-23", "秋分の日"], ["2026-10-12", "スポーツの日"], ["2026-11-03", "文化の日"], ["2026-11-23", "勤労感謝の日"],
      ["2026-10-13", null], ["2026-12-23", null],
    ];
    for (const [d, n] of cases) expect(holidayName(d), d).toBe(n);
  });
  it("2025年・2027年", () => {
    expect(holidayName("2025-03-20")).toBe("春分の日");
    expect(holidayName("2025-09-23")).toBe("秋分の日");
    expect(holidayName("2025-02-24")).toBe("振替休日");
    expect(holidayName("2027-03-22")).toBe("振替休日");  // 3/21が日曜→振替は3/22
    expect(holidayName("2027-03-21")).toBe("春分の日");
  });
});
